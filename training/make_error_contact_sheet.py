"""Create validation image contact sheets for DiagnoAI error analysis.

Run from the DiagnoAI project root:
    python -m training.make_error_contact_sheet

The script reads the validation_predictions.csv generated by audit_model.py.
It uses the absolute image_path values stored in that CSV.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable

import pandas as pd
from PIL import Image, ImageDraw, ImageFont, ImageOps


TILE_WIDTH = 260
TILE_HEIGHT = 300
IMAGE_BOX = (220, 220)
COLUMNS = 4


def load_font(size: int = 14):
    try:
        return ImageFont.truetype("arial.ttf", size)
    except OSError:
        return ImageFont.load_default()


def unique_patient_sample(
    frame: pd.DataFrame,
    limit: int = 12,
    seed: int = 42,
) -> pd.DataFrame:
    """Choose a reproducible sample with at most one image per patient."""
    frame = frame.sample(frac=1, random_state=seed)
    frame = frame.drop_duplicates(subset=["patient_id"], keep="first")
    return frame.head(limit)


def make_sheet(
    frame: pd.DataFrame,
    output_path: Path,
    title: str,
    errors: list[str],
) -> None:
    if frame.empty:
        print(f"Skipping {output_path.name}: no matching records.")
        return

    rows = (len(frame) + COLUMNS - 1) // COLUMNS
    sheet = Image.new(
        "RGB",
        (COLUMNS * TILE_WIDTH, rows * TILE_HEIGHT),
        "white",
    )
    draw = ImageDraw.Draw(sheet)
    title_font = load_font(18)
    label_font = load_font(13)

    for index, (_, record) in enumerate(frame.iterrows()):
        col = index % COLUMNS
        row = index // COLUMNS
        x = col * TILE_WIDTH
        y = row * TILE_HEIGHT

        draw.text((x + 8, y + 5), title, fill="black", font=title_font)

        image_path = Path(str(record["image_path"]))
        try:
            with Image.open(image_path) as source:
                image = ImageOps.exif_transpose(source).convert("RGB")
                image.thumbnail(IMAGE_BOX)
                canvas = Image.new("RGB", IMAGE_BOX, "#eeeeee")
                paste_x = (IMAGE_BOX[0] - image.width) // 2
                paste_y = (IMAGE_BOX[1] - image.height) // 2
                canvas.paste(image, (paste_x, paste_y))
                sheet.paste(canvas, (x + 20, y + 32))
        except Exception as exc:
            errors.append(f"{image_path}: {exc}")
            draw.rectangle(
                (x + 20, y + 32, x + 20 + IMAGE_BOX[0], y + 32 + IMAGE_BOX[1]),
                outline="red",
                width=2,
            )
            draw.text((x + 28, y + 120), "IMAGE NOT FOUND", fill="red", font=label_font)

        confidence = float(record["confidence"])
        patient = str(record["patient_id"])
        actual = str(record["actual_class"])
        predicted = str(record["predicted_class"])
        filename = image_path.name

        label_y = y + 258
        lines = [
            f"Actual: {actual} | Pred: {predicted} | Conf: {confidence:.2f}",
            f"Patient: {patient}",
            filename[:34],
        ]
        for line in lines:
            draw.text((x + 8, label_y), line, fill="black", font=label_font)
            label_y += 15

    output_path.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(output_path)
    print(f"Saved: {output_path} ({len(frame)} images)")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Create contact sheets from DiagnoAI validation predictions."
    )
    parser.add_argument(
        "--csv",
        default="models/e1_validation_audit/validation_predictions.csv",
        help="Path to validation_predictions.csv",
    )
    parser.add_argument(
        "--out-dir",
        default="models/e1_validation_audit/contact_sheets",
        help="Directory where contact sheets will be saved",
    )
    parser.add_argument(
        "--correct-samples",
        type=int,
        default=12,
        help="Maximum correctly classified BCC and ACK samples, one per patient",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    csv_path = Path(args.csv)
    output_dir = Path(args.out_dir)

    if not csv_path.is_file():
        raise FileNotFoundError(
            f"Could not find {csv_path}. Run audit_model.py first or pass --csv."
        )

    frame = pd.read_csv(csv_path)
    required = {
        "image_path",
        "patient_id",
        "actual_class",
        "predicted_class",
        "correct",
        "confidence",
    }
    missing = required - set(frame.columns)
    if missing:
        raise ValueError(f"CSV is missing required columns: {sorted(missing)}")

    frame["correct"] = frame["correct"].astype(str).str.lower().isin(
        {"true", "1", "yes"}
    )

    errors: list[str] = []

    # Include every validation MEL and SCC image, including correct predictions.
    mel = frame[frame["actual_class"] == "MEL"].sort_values(
        ["patient_id", "image_path"]
    )
    scc = frame[frame["actual_class"] == "SCC"].sort_values(
        ["patient_id", "image_path"]
    )

    # Correctly classified comparison samples, limited to one image per patient.
    bcc_correct = unique_patient_sample(
        frame[(frame["actual_class"] == "BCC") & frame["correct"]],
        limit=args.correct_samples,
    )
    ack_correct = unique_patient_sample(
        frame[(frame["actual_class"] == "ACK") & frame["correct"]],
        limit=args.correct_samples,
    )

    # All high-confidence errors, useful for spotting confident mistakes.
    high_confidence_errors = frame[
        (~frame["correct"]) & (frame["confidence"] >= 0.80)
    ].sort_values("confidence", ascending=False)

    make_sheet(mel, output_dir / "mel_validation.png", "MEL validation", errors)
    make_sheet(scc, output_dir / "scc_validation.png", "SCC validation", errors)
    make_sheet(
        bcc_correct,
        output_dir / "bcc_correct_samples.png",
        "Correct BCC examples",
        errors,
    )
    make_sheet(
        ack_correct,
        output_dir / "ack_correct_samples.png",
        "Correct ACK examples",
        errors,
    )
    make_sheet(
        high_confidence_errors,
        output_dir / "high_confidence_errors.png",
        "High-confidence errors",
        errors,
    )

    if errors:
        error_file = output_dir / "contact_sheet_errors.txt"
        error_file.write_text("\n".join(errors), encoding="utf-8")
        print(f"Some images could not be opened. Details: {error_file}")

    print("\nContact sheet generation complete.")
    print(f"Output directory: {output_dir.resolve()}")


if __name__ == "__main__":
    main()
